"""Generic reflection-orbit covering kernel.

No ARC-AGI engine names live here.  A problem instance is:
- a finite target set T on a rectangular board;
- zero, one, or two reflection axes;
- one or more finite payload shapes;
- translations for each payload.

The generated visible support is the board-clipped orbit of each translated
payload under the group generated by the available axis reflections.
Completion is target coverage: T is a subset of generated support.
"""

from dataclasses import dataclass
from typing import Iterable, Optional, Sequence

Point = tuple[int, int]

@dataclass(frozen=True)
class Axes:
    x: Optional[int] = None
    y: Optional[int] = None

@dataclass(frozen=True)
class Placement:
    x: int
    y: int

def orbit_point(p: Point, axes: Axes) -> set[Point]:
    x, y = p
    xs = {x} if axes.x is None else {x, 2 * axes.x - x}
    ys = {y} if axes.y is None else {y, 2 * axes.y - y}
    return {(xx, yy) for xx in xs for yy in ys}

def translated_shape(shape: Iterable[Point], at: Placement) -> set[Point]:
    return {(at.x + dx, at.y + dy) for dx, dy in shape}

def generated_support(
    shape: Iterable[Point],
    at: Placement,
    axes: Axes,
    width: int,
    height: int,
) -> set[Point]:
    out: set[Point] = set()
    for p in translated_shape(shape, at):
        for q in orbit_point(p, axes):
            x, y = q
            if 0 <= x < width and 0 <= y < height:
                out.add(q)
    return out

def union_support(
    shapes: Sequence[Iterable[Point]],
    placements: Sequence[Placement],
    axes: Axes,
    width: int,
    height: int,
) -> set[Point]:
    out: set[Point] = set()
    for shape, at in zip(shapes, placements):
        out |= generated_support(shape, at, axes, width, height)
    return out

def covers(
    target: Iterable[Point],
    shapes: Sequence[Iterable[Point]],
    placements: Sequence[Placement],
    axes: Axes,
    width: int,
    height: int,
) -> bool:
    return set(target) <= union_support(shapes, placements, axes, width, height)

def target_mask(
    target_index: dict[Point, int],
    shape: Iterable[Point],
    at: Placement,
    axes: Axes,
    width: int,
    height: int,
) -> int:
    mask = 0
    for p in generated_support(shape, at, axes, width, height):
        i = target_index.get(p)
        if i is not None:
            mask |= 1 << i
    return mask
