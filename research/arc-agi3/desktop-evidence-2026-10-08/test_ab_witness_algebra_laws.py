from itertools import combinations
from ab_witness_algebra import ab_or,ab_and
from ab_witness_antichain import WitnessAntichain

atoms=("A1","A2","O1","O2")
subsets=[]
for n in range(1,len(atoms)+1):
    subsets += list(combinations(atoms,n))

# Every antichain of nonempty subsets, canonicalized.
allc=set()
for mask in range(1<<len(subsets)):
    edges=[subsets[i] for i in range(len(subsets)) if (mask>>i)&1]
    allc.add(WitnessAntichain.make(edges))
A=list(allc)
print("CANONICAL_ANTICHAINS",len(A))

# Full pair laws.
for x in A:
    assert ab_or(x,x)==x
    assert ab_and(x,x)==x
for x in A:
 for y in A:
    assert ab_or(x,y)==ab_or(y,x)
    assert ab_and(x,y)==ab_and(y,x)
    assert ab_or(x,ab_and(x,y))==x
    assert ab_and(x,ab_or(x,y))==x

# Triple laws over all 168^3 would be ~4.7m; still manageable, but sample the
# complete closure generated by our witnessed families for the triple laws.
A1=WitnessAntichain.make([("A1",)])
A2=WitnessAntichain.make([("A2",)])
O1=WitnessAntichain.make([("O1",)])
O2=WitnessAntichain.make([("O2",)])
seed={WitnessAntichain.make([]),A1,A2,O1,O2}
changed=True
while changed:
    changed=False
    cur=list(seed)
    for x in cur:
     for y in cur:
      for z in (ab_or(x,y),ab_and(x,y)):
       if z not in seed:
        seed.add(z);changed=True
C=list(seed)
print("GENERATED_CLOSURE",len(C))

# Deterministic representative triple coverage spanning edge counts and forms.
C=sorted(C,key=lambda a:(len(a.edges),a.edges))
idx=sorted(set([0,1,2,3,4,5,10,20,40,80,120,len(C)-1]))
T=[C[i] for i in idx if 0<=i<len(C)]
print("TRIPLE_REPRESENTATIVES",len(T))
for x in T:
 for y in T:
  for z in T:
    assert ab_or(ab_or(x,y),z)==ab_or(x,ab_or(y,z))
    assert ab_and(ab_and(x,y),z)==ab_and(x,ab_and(y,z))
    assert ab_and(x,ab_or(y,z))==ab_or(ab_and(x,y),ab_and(x,z))
    assert ab_or(x,ab_and(y,z))==ab_and(ab_or(x,y),ab_or(x,z))

print("PASS antichain witness algebra laws")
