from __future__ import annotations

from pathlib import Path
import argparse
import json
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parent
JOBS_DIR = ROOT / "jobs"
GENERATED_DIR = ROOT / "generated"
ABILITY_MAP_PATH = ROOT / "foundation" / "ABILITY_MAP.json"


def load_ability_map():
    if not ABILITY_MAP_PATH.exists():
        return {"abilities": [], "next_project_selection": {}}
    return json.loads(ABILITY_MAP_PATH.read_text(encoding="utf-8"))


def load_jobs():
    jobs = []
    if not JOBS_DIR.exists():
        return jobs

    for path in sorted(JOBS_DIR.glob("JOB-*/job.json")):
        try:
            job = json.loads(path.read_text(encoding="utf-8"))
        except Exception as exc:
            jobs.append({
                "id": path.parent.name,
                "title": "Unreadable job record",
                "_error": str(exc),
                "_record_path": str(path.relative_to(ROOT)),
            })
            continue

        job["_record_path"] = str(path.relative_to(ROOT))
        job["_folder"] = str(path.parent.relative_to(ROOT))
        jobs.append(job)

    def job_number(job):
        raw = str(job.get("id", "JOB-999999"))
        try:
            return int(raw.split("-")[-1])
        except Exception:
            return 999999

    return sorted(jobs, key=job_number)


def strongest_label(job):
    status = str(job.get("status", "")).lower()
    submission = str(job.get("submission_status", "")).lower()
    payment = str(job.get("payment_status", "")).lower()

    if payment in {"paid", "received"} or status == "paid":
        return "Paid technical work"
    if submission in {"accepted", "won"}:
        return "Accepted technical work"
    if submission == "submitted":
        return "Submitted technical project"
    return "Independent technical project"


def compact_result(job):
    result = str(job.get("result", "")).strip()
    return result if result else "No verified result recorded"


def evidence_count(job):
    evidence = job.get("evidence", [])
    return len(evidence) if isinstance(evidence, list) else 0


def render_jobs(jobs):
    rows = []
    for j in jobs:
        rows.append(
            f"| {j.get('id','')} | [{j.get('title','')}]({j.get('_folder','')}/JOB.md) | "
            f"{j.get('reward_observed','')} | {j.get('status','')} | "
            f"{j.get('submission_status','')} | {compact_result(j)} | "
            f"[Open]({j.get('_folder','')}/JOB.md) |"
        )

    return """# JOBS — Generated Historical Ledger

> AUTO-GENERATED from `jobs/*/job.json`. Do not edit this file by hand.

| ID | Job | Pay / prize observed | Work status | Submission | Result | Record |
|---|---|---:|---|---|---|---|
""" + "\n".join(rows) + "\n"


def render_tasks(jobs):
    actionable = [
        j for j in jobs
        if str(j.get("status", "")).lower()
        not in {"paid", "closed"}
    ]

    lines = [
        "# TASKS — Generated Current Work",
        "",
        "> AUTO-GENERATED from `jobs/*/job.json`. Do not edit this file by hand.",
        "",
    ]

    if not actionable:
        lines.append("No current tasks.")
        return "\n".join(lines) + "\n"

    for j in actionable:
        lines += [
            f"## [{j.get('id','')} — {j.get('title','')}]({j.get('_folder','')}/JOB.md)",
            f"- status: {j.get('status','')}",
            f"- {j.get('preferred_referent','📍 preferred referent not recorded')}",
            f"- next movement: {j.get('next_movement','')}",
            f"- acceptance: {j.get('acceptance','')}",
            f"- reward observed: {j.get('reward_observed','')}",
            f"- submission: {j.get('submission_status','')}",
            f"- record: [{j.get('_folder','')}/]({j.get('_folder','')}/JOB.md)",
            "",
        ]
    return "\n".join(lines)


def render_resume(jobs, ability_map=None):
    ability_map = ability_map or load_ability_map()
    lines = [
        "# James — Generated Resume View",
        "",
        "> AUTO-GENERATED from repository evidence.",
        "> Ability claims come from Foundation/job witnesses; planned work does not upgrade a category.",
        "> Unsubmitted/unpaid work remains labeled as independent project work.",
        "",
        "## Professional Summary",
        "",
        "Technical problem solver with tested evidence across software/platform engineering, "
        "data engineering, database systems, automation, data analysis, scraping, CI, "
        "observability, reliability, and spreadsheet engineering.",
        "",
        "## Demonstrated Abilities",
        "",
    ]

    for item in ability_map.get("abilities", []):
        state = item.get("state", "unwitnessed")
        if state not in {"tested", "deployed_operating"}:
            continue
        supports = item.get("supports", [])
        lines.append(f"### {item.get('ability', 'Unnamed ability')} — {state}")
        if supports:
            lines.append("- Evidence supports: " + ", ".join(supports) + ".")
        evidence = item.get("evidence", [])
        if evidence:
            lines.append(f"- Inspectable witnesses: {len(evidence)}")
        lines.append("")

    lines += [
        "## Partial / Not Yet Claimed",
        "",
    ]

    for item in ability_map.get("abilities", []):
        state = item.get("state", "unwitnessed")
        if state == "tested" or state == "deployed_operating":
            continue
        lines.append(
            f"- **{item.get('ability', 'Unnamed ability')} — {state}:** "
            f"{item.get('next_gap', 'No next gap recorded.')}"
        )

    lines += [
        "",
        "## Selected Technical Projects",
        "",
    ]

    for j in jobs:
        lines += [
            f"### {j.get('title','Untitled project')}",
            f"**{strongest_label(j)}**",
            "",
            f"- Result: {compact_result(j)}",
            f"- External boundary: {j.get('boundary','Not recorded')}",
            f"- Acceptance: {j.get('acceptance','Not recorded')}",
            f"- Evidence artifacts recorded: {evidence_count(j)}",
        ]

        notes = j.get("resume_bullets")
        if isinstance(notes, list):
            for bullet in notes:
                lines.append(f"- {bullet}")

        lines += [""]

    return "\n".join(lines)


def render_portfolio(jobs):
    lines = [
        "# PORTFOLIO — Generated Evidence View",
        "",
        "> AUTO-GENERATED from `jobs/*/job.json`.",
        "",
    ]
    for j in jobs:
        lines += [
            f"## {j.get('id','')} — {j.get('title','')}",
            f"- Label: {strongest_label(j)}",
            f"- Source: {j.get('source_platform','')}",
            f"- Source URL: {j.get('source_url','')}",
            f"- Reward observed: {j.get('reward_observed','')}",
            f"- Status: {j.get('status','')}",
            f"- Submission: {j.get('submission_status','')}",
            f"- Preferred referent: {j.get('preferred_referent','')}",
            f"- Result: {compact_result(j)}",
            f"- Acceptance: {j.get('acceptance','')}",
            "",
            "### Evidence",
        ]
        evidence = j.get("evidence", [])
        if isinstance(evidence, list) and evidence:
            for item in evidence:
                lines.append(f"- `{j.get('_folder','')}/{item}`")
        else:
            lines.append("- No evidence files recorded.")
        lines += [""]

    return "\n".join(lines)


def render_ability_map(ability_map):
    lines = [
        "# ABILITY MAP — Generated Evidence Projection",
        "",
        "> AUTO-GENERATED from foundation/ABILITY_MAP.json.",
        "> This is a projection over evidence, not a self-rating.",
        "",
        "| Ability | State | Witnesses | Next gap |",
        "|---|---|---:|---|",
    ]

    for item in ability_map.get("abilities", []):
        lines.append(
            f"| {item.get('ability','')} | {item.get('state','')} | "
            f"{len(item.get('evidence', []))} | {item.get('next_gap','')} |"
        )

    selection = ability_map.get("next_project_selection", {})
    if selection:
        lines += [
            "",
            "## Next Evidence Build",
            "",
            f"- Selected gap: {selection.get('selected_gap','')}",
            f"- Reason: {selection.get('reason','')}",
        ]

    return "\n".join(lines) + "\n"


def render_work_summary(jobs):
    tested = sum(
        1 for j in jobs
        if str(j.get("status", "")).lower()
        in {"tested", "ready_to_submit", "submitted", "paid", "closed"}
    )
    submitted = sum(
        1 for j in jobs
        if str(j.get("submission_status", "")).lower()
        in {"submitted", "accepted", "won"}
    )
    paid = sum(
        1 for j in jobs
        if str(j.get("payment_status", "")).lower() in {"paid", "received"}
        or str(j.get("status", "")).lower() == "paid"
    )

    lines = [
        "# WORK SUMMARY — Generated",
        "",
        "> AUTO-GENERATED from current job records.",
        "",
        f"- Jobs recorded: {len(jobs)}",
        f"- Tested/completed enough to verify: {tested}",
        f"- Submitted/accepted: {submitted}",
        f"- Paid: {paid}",
        "",
        "## Records",
    ]

    for j in jobs:
        lines.append(
            f"- {j.get('id','')} — {j.get('title','')} — "
            f"{j.get('status','')} — {compact_result(j)}"
        )

    return "\n".join(lines) + "\n"


def render_json_snapshot(jobs):
    clean = []
    for j in jobs:
        item = dict(j)
        clean.append(item)

    return json.dumps(
        {
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "jobs": clean,
        },
        indent=2,
        ensure_ascii=False,
    ) + "\n"


def generate_all(output_dir: Path = GENERATED_DIR):
    output_dir.mkdir(parents=True, exist_ok=True)
    jobs = load_jobs()
    ability_map = load_ability_map()

    outputs = {
        "JOBS.md": render_jobs(jobs),
        "TASKS.md": render_tasks(jobs),
        "RESUME.md": render_resume(jobs, ability_map),
        "ABILITY_MAP.md": render_ability_map(ability_map),
        "PORTFOLIO.md": render_portfolio(jobs),
        "WORK_SUMMARY.md": render_work_summary(jobs),
        "jobs_snapshot.json": render_json_snapshot(jobs),
    }

    for name, content in outputs.items():
        (output_dir / name).write_text(content, encoding="utf-8")

    return outputs


def main():
    parser = argparse.ArgumentParser(
        description="Generate current repo outputs from jobs/*/job.json."
    )
    parser.add_argument(
        "--output-dir",
        default=str(GENERATED_DIR),
        help="Directory for generated views (default: ./generated)",
    )
    parser.add_argument(
        "--print",
        dest="print_view",
        choices=["jobs", "tasks", "resume", "portfolio", "summary", "abilities"],
        help="Print one generated view to stdout.",
    )
    args = parser.parse_args()

    jobs = load_jobs()
    ability_map = load_ability_map()

    if args.print_view:
        if args.print_view == "abilities":
            print(render_ability_map(ability_map))
            return
        if args.print_view == "resume":
            print(render_resume(jobs, ability_map))
            return
        views = {
            "jobs": render_jobs,
            "tasks": render_tasks,
            "portfolio": render_portfolio,
            "summary": render_work_summary,
        }
        print(views[args.print_view](jobs))
        return

    outputs = generate_all(Path(args.output_dir))
    print(f"Generated {len(outputs)} views from {len(jobs)} job records.")


if __name__ == "__main__":
    main()
