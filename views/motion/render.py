def read_work_state(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf8"))
    expected = {"MOVE", "WALL", "UNKNOWN", "PARTIAL"}
    p = data.get("protocol_results")
    if (not isinstance(p,dict) or set(p) != expected
            or any(type(v) is not int or v < 0 for v in p.values())
            or type(data.get("jobs")) is not int or data["jobs"] < 0
            or sum(p.values()) != data["jobs"]):
        raise ValueError("malformed or inconsistent recorded work-state counts")
    return data


def render_work_state(data: dict) -> str:
    p = data["protocol_results"]
    height = 350
    svg = svg_start("Workstation recorded movement outcomes",
                    "Recorded protocol outcomes from views/work_state.json. "
                    "Animated marks do not signify running workers or new jobs.", height)
    svg += title_block("EXISTING WORKSTATION / RECORDED RESULTS",
                       "Movement and walls",
                       f'{data["jobs"]} recorded jobs · public aggregate, not worker health')
    for n,(name,color) in enumerate((("MOVE",CYAN),("WALL",VIOLET),
                                    ("UNKNOWN",BLUE),("PARTIAL",SILVER))):
        y=161+n*43
        svg += (f'<text x="47" y="{y}" fill="{color}" font-size="16">{name}</text>'
                f'<rect x="191" y="{y-16}" width="650" height="20" rx="8" fill="#1a2a3e"/>')
        width=650*p[name]/max(1,data["jobs"])
        if width:
            svg += (f'<rect x="191" y="{y-16}" width="{width:.1f}" height="20" rx="8" fill="{color}" fill-opacity=".23"/>'
                    f'<path class="signal slow" d="M195 {y-6}H{191+width:.1f}" stroke="{color}" '
                    'stroke-width="4" fill="none"/>')
        svg += f'<text x="876" y="{y}" fill="{SILVER}" font-size="20">{p[name]}</text>'
    svg += ('<text x="47" y="326" fill="#acbfd1" font-size="13">'
            'Counts are committed records, not live executions or source-edit witnesses.</text></svg>')
    return svg


def read_world_snapshot(path: Path) -> dict:
    s = json.loads(path.read_text(encoding="utf8"))
    if (s.get("schema") != "public-world-continuity/v1"
            or not isinstance(s.get("checked_at"), str)
            or not isinstance(s.get("relationship"), dict)
            or not isinstance(s.get("sources"), dict)
            or not isinstance(s.get("unjoined"), list)):
        raise ValueError("unknown original world observation schema")
    relation=s["relationship"]
    if (type(relation.get("matched_by_declared_url_rule")) is not bool
            or not isinstance(relation.get("evidence"),list)
            or not isinstance(s["sources"].get("usgs",{}).get("count"),int)):
        raise ValueError("incomplete source-owner relationship")
    if s["sources"]["usgs"]["count"] < 0:
        raise ValueError("negative source count")
    return s


def render_world(s: dict) -> str:
    linked=s["relationship"]["matched_by_declared_url_rule"]
    usgs=s["sources"]["usgs"]["count"]
    stamp=s["checked_at"][:19].replace("T"," ")+" UTC"
    svg=svg_start("Public observations: evidence-backed versus unjoined paths",
                  "Snapshot checked " + stamp + ". Source-owned URL metadata "
                  + ("supports" if linked else "does not support")
                  + " the GitHub/PyPI relationship; USGS remains separate.", 405)
    svg+=title_block("SOURCE OBSERVATIONS / SNAPSHOT",
                     "Some paths connect. Others stay open.",
                     "Source timestamp: "+stamp+" · not a live data feed")
    gh=s["observations"]["github"]["payload"]["full_name"]
    package=s["observations"]["pypi"]["payload"]["name"]
    if not isinstance(gh,str) or not isinstance(package,str):
        raise ValueError("missing native names")
    cards=((55,178,"GITHUB",gh,CYAN),
           (565,178,"PYPI",package,BLUE),
           (55,308,"USGS",str(usgs)+" earthquake events",VIOLET))
    for x,y,title,subtitle,color in cards:
        w=445 if title!="USGS" else 1010
        svg+=(f'<rect x="{x}" y="{y-31}" width="{w}" height="76" rx="11" '
              f'fill="{PANEL}" stroke="{color}" stroke-opacity=".6"/>'
              f'<text x="{x+20}" y="{y-5}" font-size="12" fill="{color}">{title}</text>'
              f'<text x="{x+20}" y="{y+23}" font-size="20" fill="{SILVER}">{escape(subtitle)}</text>')
    if linked:
        svg+=(f'<path class="signal" d="M503 181H562" stroke="{CYAN}" '
              f'fill="none" stroke-width="4"/>'
              f'<text x="420" y="261" fill="{CYAN}" font-size="15">'
              'Matched by declared URL rule ONLY</text>')
    else:
        svg+='<text x="425" y="261" fill="#d7b7a5" font-size="14">No supported source match</text>'
    svg+=(f'<circle class="ring" cx="975" cy="315" r="23" fill="none" '
          f'stroke="{VIOLET}" stroke-dasharray="4 12" stroke-width="2"/>'
          f'<text x="69" y="388" font-size="13" fill="#b3c6d9">'
          'USGS unjoined; metadata relation is not authenticated ownership or scientific proof.</text>'
          '</svg>')
    return svg


def produce(source_root: Path = ROOT) -> dict[str,str]:
    finite = finite_observation()
    work = read_work_state(source_root/"views/work_state.json")
    world = read_world_snapshot(source_root/"views/world-continuity/latest.json")
    return {
        "finite-motion.svg":render_finite(finite),
        "workstation-motion.svg":render_work_state(work),
        "world-motion.svg":render_world(world),
    }


def generate(out: Path) -> None:
    images=produce()
    for name,source in images.items():
        if ("<script" in source or "<image" in source or "href=" in source
                or "https://" in source or "http://" in source.replace(
                    'xmlns="http://www.w3.org/2000/svg"', "")):
            raise ValueError("external/script content must not appear in SVG")
        ET.fromstring(source)
        if not source.endswith("</svg>"):
            raise ValueError("invalid self-contained SVG")
    out.mkdir(parents=True, exist_ok=True)
    for name,source in images.items():
        temp_name=None
        try:
            with tempfile.NamedTemporaryFile(mode="w", dir=out,
                                              encoding="utf8", delete=False) as stream:
                temp_name=stream.name
                stream.write(source+"\n")
            os.replace(temp_name, out/name)
        finally:
            if temp_name and os.path.exists(temp_name):
                os.unlink(temp_name)


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path,
                        default=ROOT/"views/motion")
    args=parser.parse_args()
    generate(args.out_dir)
    print("Generated three source-owned SVG animations; no worker launched.")
