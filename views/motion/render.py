def svg_start(title: str, description: str, height: int = 430) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="1100" height="{height}" '
            f'viewBox="0 0 1100 {height}" role="img" aria-labelledby="title desc">'
            f'<title id="title">{escape(title)}</title>'
            f'<desc id="desc">{escape(description)}</desc>'
            f'<style>{CSS}</style>'
            f'<rect width="1100" height="{height}" rx="14" fill="{BG}"/>'
            f'<rect x="12" y="12" width="1076" height="{height-24}" rx="10" '
            f'fill="none" stroke="#344967"/>'
            f'<g stroke="#30445e" stroke-opacity=".24">'
            + "".join(f'<path d="M{x} 20V{height-20}"/>' for x in range(40,1100,44))
            + "</g>")


def title_block(kicker: str, heading: str, detail: str) -> str:
    return (f'<text x="42" y="51" font-size="13" letter-spacing="2.1" fill="{CYAN}">'
            f'{escape(kicker)}</text>'
            f'<text x="42" y="96" font-size="30" font-weight="bold" fill="#f3f8ff">'
            f'{escape(heading)}</text>'
            f'<text x="43" y="123" font-size="14" fill="#b6c8df">'
            f'{escape(detail)}</text>')


def state_label(state: tuple[int, ...]) -> str:
    return "(" + ",".join(str(x) for x in state) + ")"


def finite_observation() -> dict:
    """All displayed transition endpoints come from the real World.step."""
    world = World(3, (0, 1, 2))
    s = world.origin
    a = world.step(s, "A")
    b = world.step(s, "B")
    ab = world.step(a, "B")
    ba = world.step(b, "A")
    aaa = world.apply("AAA")
    if world.apply("AB") != ab or world.apply("BA") != ba:
        raise ValueError("native finite action order changed")
    return {"schema": "native-finite-world/declared-phi-012",
            "origin": s, "A": a, "B": b, "AB": ab, "BA": ba,
            "A3": aaa, "noncommuting": ab != ba,
            "cycle": aaa == s, "reachable_states": len(world.reachable())}


